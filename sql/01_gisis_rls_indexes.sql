CREATE OR REPLACE FUNCTION public.trg_set_operator_stamp()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE jwt_email text;
BEGIN
  jwt_email := COALESCE(auth.jwt() ->> 'email', NULL);
  NEW.updated_at := now();
  IF jwt_email IS NOT NULL THEN NEW.updated_by := jwt_email; END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS set_facility_stamp ON public.port_facilities;
CREATE TRIGGER set_facility_stamp
  BEFORE INSERT OR UPDATE ON public.port_facilities
  FOR EACH ROW EXECUTE FUNCTION public.trg_set_operator_stamp();

